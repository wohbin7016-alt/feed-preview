const DB_NAME = 'moa-feed-preview';
const DB_VERSION = 1;
let dbPromise;

function openDatabase() {
  if (dbPromise) return dbPromise;
  dbPromise = new Promise((resolve, reject) => {
    if (!globalThis.indexedDB) return reject(new Error('이 브라우저에서는 사진 저장을 사용할 수 없어요.'));
    const request = indexedDB.open(DB_NAME, DB_VERSION);
    request.onupgradeneeded = () => {
      const db = request.result;
      if (!db.objectStoreNames.contains('photos')) db.createObjectStore('photos', { keyPath: 'id' });
      if (!db.objectStoreNames.contains('meta')) db.createObjectStore('meta');
    };
    request.onerror = () => reject(request.error);
    request.onblocked = () => reject(new Error('다른 모아 탭을 닫은 뒤 새로고침해 주세요.'));
    request.onsuccess = () => {
      const db = request.result;
      db.onversionchange = () => { db.close(); dbPromise = undefined; };
      resolve(db);
    };
  }).catch(error => { dbPromise = undefined; throw error; });
  return dbPromise;
}

export async function loadState() {
  const db = await openDatabase();
  return new Promise((resolve, reject) => {
    const tx = db.transaction(['photos', 'meta'], 'readonly');
    const photosRequest = tx.objectStore('photos').getAll();
    const metaRequest = tx.objectStore('meta').get('layout');
    tx.oncomplete = () => {
      const photos = new Map(photosRequest.result.map(photo => [photo.id, photo]));
      const layout = metaRequest.result || {};
      const order = [...new Set(layout.order || [])].filter(id => photos.has(id));
      const undo = layout.undo && photos.has(layout.undo.id) && !order.includes(layout.undo.id) ? layout.undo : null;
      resolve({ photos, order, undo, ratio: layout.ratio === 'square' ? 'square' : 'portrait', revision: Number(layout.revision) || 0 });
    };
    tx.onerror = () => reject(tx.error || new Error('저장한 사진을 불러오지 못했어요.'));
    tx.onabort = () => reject(tx.error || new Error('사진 불러오기가 중단됐어요.'));
  });
}

// The layout and changed blobs always commit together. Resolve only after the
// transaction commits, never after an individual IDB request succeeds.
export async function commitState(state, { put = [], remove = [] } = {}) {
  const db = await openDatabase();
  return new Promise((resolve, reject) => {
    const tx = db.transaction(['photos', 'meta'], 'readwrite');
    const photoStore = tx.objectStore('photos');
    const metaStore = tx.objectStore('meta');
    let conflict = false;
    let writeError = null;
    const revisionRequest = metaStore.get('layout');
    revisionRequest.onsuccess = () => {
      const currentRevision = Number(revisionRequest.result?.revision) || 0;
      if (currentRevision !== state.revision) {
        conflict = true;
        tx.abort();
        return;
      }
      try {
        for (const id of remove) photoStore.delete(id);
        for (const photo of put) photoStore.put(photo);
        metaStore.put({ order: state.order, ratio: state.ratio, undo: state.undo, revision: currentRevision + 1 }, 'layout');
      } catch (error) {
        // Preserve synchronous DOMExceptions instead of losing their name to
        // the generic AbortError generated by an uncaught event-handler error.
        writeError = error;
        try { tx.abort(); } catch { reject(writeError); }
      }
    };
    tx.oncomplete = () => resolve(state.revision + 1);
    tx.onerror = () => reject(writeError || tx.error || new Error('사진을 저장하지 못했어요.'));
    tx.onabort = () => {
      const error = conflict ? new Error('다른 탭에서 피드가 바뀌었어요. 최신 피드를 다시 불러왔어요.') : writeError || tx.error || new Error('저장이 중단됐어요.');
      if (conflict) error.name = 'ConflictError';
      reject(error);
    };
  });
}
